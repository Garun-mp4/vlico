"""Approved first message for the VLICO partnership campaign."""
from urllib.parse import urlencode

from .partner_segments import segment_group


def partner_url(channel):
    if channel not in {"whatsapp", "telegram"}:
        raise ValueError("Unsupported partnership channel")
    return "https://vlico39.ru/partners/?" + urlencode({
        "utm_source": channel, "utm_medium": "messenger", "utm_campaign": "partner_network",
    })


def first_message(props, channel):
    if segment_group(props.get("partnersegment")) is None:
        raise ValueError("Partnership audience requires review")
    marker = "*" if channel == "whatsapp" else "**"

    def bold(text):
        return marker + text + marker

    offer = "сложные потолочные решения, встроенное освещение и грамотный монтаж"
    question = "Подскажите, у вас сейчас есть проекты, где могла бы пригодиться наша помощь?"
    return (
        "Здравствуйте! 👋\n\n"
        f"Я Виктория, студия потолочных решений {bold('VLICO')}, Калининград.\n\n"
        f"Мы подключаемся к проектам дизайнеров и строительных компаний, когда нужны {bold(offer)}.\n\n"
        "Можем бесплатно посмотреть ваш проект, предложить технические решения и помочь избежать ошибок при реализации.\n\n"
        f"Примеры наших работ:\n{partner_url(channel)}\n\n"
        f"{bold(question)}"
    )


